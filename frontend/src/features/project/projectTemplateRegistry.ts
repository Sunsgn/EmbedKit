import type { Chip, FileNode } from '../../types';

export const PROJECT_TEMPLATE_API_VERSION = 1 as const;
export const PROJECT_TEMPLATE_NAME_MAX_LENGTH = 80;

export interface ProjectTemplateContext {
  projectName: string;
  chip?: Chip;
}

export interface ProjectTemplateAdapter {
  id: string;
  version: string;
  apiVersion: typeof PROJECT_TEMPLATE_API_VERSION;
  scope: string;
  supports(context: Readonly<ProjectTemplateContext>): boolean;
  generate(context: Readonly<ProjectTemplateContext>): FileNode[];
}

export interface ProjectTemplateResult {
  adapterId: string;
  adapterVersion: string;
  files: FileNode[];
  fallbackReason?: 'no_adapter' | 'adapter_failed' | 'invalid_output';
}

function normalizeProjectName(value: string): string {
  const printable = Array.from(value, character => {
    const code = character.charCodeAt(0);
    return code <= 31 || code === 127 ? ' ' : character;
  }).join('');
  const normalized = printable.replace(/\s+/g, ' ').trim();
  return (normalized || 'embedkit_project').slice(0, PROJECT_TEMPLATE_NAME_MAX_LENGTH);
}

function escapeCString(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function describeTarget(chip?: Chip): string {
  if (!chip) return 'Not selected';
  return `${chip.manufacturer} ${chip.name}`.trim();
}

function createGenericFiles(context: Readonly<ProjectTemplateContext>): FileNode[] {
  const projectName = normalizeProjectName(context.projectName);
  const targetName = describeTarget(context.chip);
  const targetCore = context.chip?.cores?.trim() || 'Unknown';
  const source = `/**
 * ${projectName}
 * Platform-independent source scaffold generated by EmbedKit.
 *
 * This file intentionally makes no SDK, startup, linker, RTOS or toolchain
 * assumptions. Connect the appropriate adapter or existing vendor project
 * before building for real hardware.
 */
#include <stdint.h>
#include "project_config.h"

static void platform_initialize(void)
{
    /* TODO: initialize startup, clocks, pins and required peripherals. */
}

int main(void)
{
    platform_initialize();

    for (;;) {
        /* TODO: run the application, event loop or scheduler integration. */
    }
}
`;
  const header = `#ifndef EMBEDKIT_PROJECT_CONFIG_H
#define EMBEDKIT_PROJECT_CONFIG_H

#define PROJECT_NAME "${escapeCString(projectName)}"
#define TARGET_NAME "${escapeCString(targetName)}"
#define TARGET_CORE "${escapeCString(targetCore)}"

#endif
`;
  const readme = `# ${projectName}

This is a platform-independent source scaffold. It is not a complete or directly buildable firmware project.

## Selected target metadata

- Target: ${targetName}
- Core: ${targetCore}
- Series: ${context.chip?.series?.trim() || 'Unknown'}

## Before building

1. Select or import the real SDK, startup code and linker configuration.
2. Confirm the board clock, memory map, pin assignment and peripheral instances from primary documentation.
3. Configure the existing vendor IDE or toolchain project; EmbedKit does not assume a compiler or replace it.
4. Complete \`platform_initialize()\` and record the exact hardware and build configuration used for verification.

Unknown target details are preserved as unknown instead of being inferred from a similar family.
`;

  return [
    { name: 'main.c', path: '/Src/main.c', content: source, language: 'c' },
    { name: 'project_config.h', path: '/Inc/project_config.h', content: header, language: 'h' },
    { name: 'README.md', path: '/README.md', content: readme, language: 'text' },
  ];
}

function isValidTemplate(files: FileNode[]): boolean {
  if (files.length === 0) return false;
  const paths = new Set<string>();
  return files.every(file => {
    const path = file.path.toLowerCase();
    if (!file.name || !file.path.startsWith('/') || file.path.includes('..') || paths.has(path)) return false;
    paths.add(path);
    return typeof file.content === 'string';
  });
}

const genericAdapter: ProjectTemplateAdapter = {
  id: 'embedkit.generic-source',
  version: '1.0.0',
  apiVersion: PROJECT_TEMPLATE_API_VERSION,
  scope: 'Any bare-metal, event-driven, RTOS or unknown embedded target; source scaffold only.',
  supports: () => true,
  generate: createGenericFiles,
};

export function createProjectTemplate(
  context: ProjectTemplateContext,
  adapters: readonly ProjectTemplateAdapter[] = [],
): ProjectTemplateResult {
  const normalizedContext = { ...context, projectName: normalizeProjectName(context.projectName) };
  let selected: ProjectTemplateAdapter | undefined;

  try {
    selected = adapters.find(adapter =>
      adapter.apiVersion === PROJECT_TEMPLATE_API_VERSION && adapter.supports(normalizedContext),
    );
  } catch {
    return fallback(normalizedContext, 'adapter_failed');
  }

  if (!selected) return fallback(normalizedContext, adapters.length > 0 ? 'no_adapter' : undefined);

  try {
    const files = selected.generate(normalizedContext);
    if (!isValidTemplate(files)) return fallback(normalizedContext, 'invalid_output');
    return { adapterId: selected.id, adapterVersion: selected.version, files };
  } catch {
    return fallback(normalizedContext, 'adapter_failed');
  }
}

function fallback(
  context: Readonly<ProjectTemplateContext>,
  fallbackReason?: ProjectTemplateResult['fallbackReason'],
): ProjectTemplateResult {
  return {
    adapterId: genericAdapter.id,
    adapterVersion: genericAdapter.version,
    files: genericAdapter.generate(context),
    ...(fallbackReason ? { fallbackReason } : {}),
  };
}
